#!/usr/bin/env python3
"""
Dataset report for the TDC DrugBank DDI export.

    python scripts/08_dataset_report.py

Writes reports/dataset_report.md, reports/degree_distribution.csv and
reports/interaction_types.csv.

This is the first thing to run against any new data drop, and its output is
what you check the provider's stated counts against. Discrepancies are the
interesting part.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np
import pandas as pd

from ddinet.data import tdc_drugbank as tdc

REPORTS = Path(__file__).resolve().parents[1] / "reports"

#: Counts stated by the project owner when the file was committed. The report
#: checks against these rather than trusting either side.
CLAIMED = {"pairs": 191808, "drugs": 1706, "types": 86}


def main() -> int:
    pd.set_option("display.width", 200)
    print("Reading data/raw/drugbank.tab.gz ...")
    report = tdc.build_report()
    drugs = tdc.load_drugs()
    pairs = tdc.load_pairs()

    deg = report.degree
    q = deg.quantile([0.0, 0.25, 0.5, 0.75, 0.9, 0.99, 1.0])

    lines: list[str] = []
    w = lines.append

    w("# Dataset report - TDC DrugBank DDI\n")
    w("Generated by `scripts/08_dataset_report.py`. Source file: "
      "`data/raw/drugbank.tab.gz`.\n")

    w("## Reconciliation with the stated counts\n")
    w("| Quantity | Stated | Measured | Match |")
    w("|---|---|---|---|")
    w(f"| Rows in file | {CLAIMED['pairs']:,} | {report.n_rows:,} | "
      f"{'yes' if report.n_rows == CLAIMED['pairs'] else 'NO'} |")
    w(f"| Unique drugs | {CLAIMED['drugs']:,} | {report.n_drugs:,} | "
      f"{'yes' if report.n_drugs == CLAIMED['drugs'] else 'NO'} |")
    w(f"| Interaction types | {CLAIMED['types']} | {report.n_types} | "
      f"{'yes' if report.n_types == CLAIMED['types'] else 'NO'} |")
    w(f"| Unique **unordered pairs** | not stated | {report.n_pairs:,} | see below |")
    w("")
    w(f"**Discrepancy found.** The file has {report.n_rows:,} rows but only "
      f"{report.n_pairs:,} unique unordered pairs - a difference of "
      f"{report.n_rows - report.n_pairs}.")
    w("")
    w(f"Cause: {report.n_multitype_pairs} unordered pairs are recorded twice with "
      "*different* `Y` values. There are **no exact duplicates**. A drug pair can "
      "carry more than one documented mechanism at once, so this is a genuine "
      "multi-label structure rather than dirty data.")
    w("")
    w("Consequence for the experiments:")
    w("")
    w("- **Binary task** (does this pair interact): use the "
      f"{report.n_pairs:,} unordered pairs. Counting rows would double-count "
      "406 facts and, worse, could place the two copies of one fact on opposite "
      "sides of a split.")
    w(f"- **86-class typing task**: genuinely multi-label for those "
      f"{report.n_multitype_pairs} pairs. `load_pairs()` keeps every type in "
      "`y_types` so neither view is lost.")
    w("")

    w("## ⚠ There are no negative examples\n")
    w("`Y` is the interaction **type** (1..86), not a binary label. Every row is "
      "a documented interaction. The dataset contains no non-interacting pairs "
      "at all, so any binary experiment must generate its own negatives.")
    w("")
    w(f"Graph density: {report.n_pairs:,} pairs out of "
      f"{report.n_drugs * (report.n_drugs - 1) // 2:,} possible = "
      f"**{100 * report.density:.2f}%**. The remaining "
      f"{100 * (1 - report.density):.2f}% is *unlabelled*, not negative.")
    w("")
    w("Negative-sampling options and their drawbacks are recorded in "
      "`LIMITATIONS.md` (L1.3). **The choice is not made in code yet.**")
    w("")

    w("## Structures\n")
    w(f"- Valid SMILES by RDKit: **{report.n_valid_smiles:,} / {report.n_drugs:,} "
      f"= {100 * report.smiles_valid_fraction:.2f}%**")
    w(f"- DrugBank IDs whose SMILES differs between rows: "
      f"**{len(report.inconsistent_smiles_ids)}**")
    w(f"- Distinct structures sharing an InChIKey: "
      f"**{len(report.duplicate_structures)}**")
    w("")
    if report.invalid_smiles_ids:
        w("### Unparseable structures\n")
        for drug_id in report.invalid_smiles_ids:
            row = drugs.loc[drugs.drugbank_id == drug_id].iloc[0]
            n_pairs = int(((pairs.drug_a == drug_id) | (pairs.drug_b == drug_id)).sum())
            w(f"- **{drug_id}** — appears in {n_pairs} pairs")
            w(f"  - `{row.smiles}`")
        w("")
        w("This is an upstream defect in the export, not a parsing bug on our "
          "side: the SMILES uses malformed ring-closure syntax (`C-1=`, `\\-1N2`) "
          "which is not valid SMILES. RDKit reports a syntax error at the "
          "ring-bond token.")
        w("")
        w("**Decision required before modelling.** A drug with no parseable "
          "structure cannot be given ECFP4 features, so it must either be "
          "dropped (losing its pairs) or carried with an all-zero feature vector "
          "plus a missingness flag. The loader keeps it with `valid=False` and "
          "makes no decision. Recorded in `LIMITATIONS.md`.")
        w("")

    w("## Drug interaction degree\n")
    w("How many distinct partners each drug has, over unordered pairs.\n")
    w("| Statistic | Value |")
    w("|---|---|")
    w(f"| Drugs | {report.n_drugs:,} |")
    w(f"| Mean degree | {deg.mean():.1f} |")
    w(f"| Std | {deg.std():.1f} |")
    for label, quant in zip(("min", "25%", "median", "75%", "90%", "99%", "max"), q):
        w(f"| {label} | {int(quant)} |")
    w(f"| Drugs with degree 0 | {int((deg == 0).sum())} |")
    w(f"| Drugs with degree 1 | {int((deg == 1).sum())} |")
    w("")
    w("Top 10 hubs:\n")
    w("| DrugBank ID | Degree |")
    w("|---|---|")
    for drug_id, d in deg.head(10).items():
        w(f"| {drug_id} | {int(d)} |")
    w("")
    w(f"The degree distribution is heavily skewed: the median drug has "
      f"{int(q.loc[0.5])} partners while the top hub has {int(deg.max())}. "
      "This is exactly the structure that makes a random pair split leak - a hub's "
      "edges get spread across all three splits - and it is why negative sampling "
      "must control for degree.")
    w("")

    w("## Interaction types\n")
    tv = report.type_counts
    w(f"{len(tv)} types. The distribution is extremely imbalanced: the largest "
      f"class holds {tv.n_rows.max():,} rows "
      f"({100 * tv.n_rows.max() / report.n_rows:.1f}% of the corpus) while the "
      f"smallest holds {tv.n_rows.min()}.")
    w("")
    w("| Y | Rows | Share | Description |")
    w("|---|---|---|---|")
    for r in tv.head(15).itertuples():
        w(f"| {r.y} | {r.n_rows:,} | {100 * r.n_rows / report.n_rows:.1f}% | "
          f"{r.description} |")
    w("")
    w("Rarest 5:\n")
    w("| Y | Rows | Description |")
    w("|---|---|---|")
    for r in tv.tail(5).itertuples():
        w(f"| {r.y} | {r.n_rows} | {r.description} |")
    w("")
    w("With classes this rare, a stratified split cannot guarantee every type "
      "appears in every fold, and per-class metrics for the tail will have very "
      "wide intervals. Report macro-averaged metrics with that caveat, or "
      "restrict the typing task to classes above a stated frequency floor.")
    w("")

    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "dataset_report.md").write_text("\n".join(lines))
    deg.rename("degree").to_frame().to_csv(REPORTS / "degree_distribution.csv",
                                           index_label="drugbank_id")
    tv.to_csv(REPORTS / "interaction_types.csv", index=False)

    print("\n".join(lines[:0]) or "", end="")
    print(f"\nrows={report.n_rows:,}  unordered pairs={report.n_pairs:,}  "
          f"drugs={report.n_drugs:,}  types={report.n_types}")
    print(f"valid SMILES: {report.n_valid_smiles}/{report.n_drugs} "
          f"({100 * report.smiles_valid_fraction:.2f}%)")
    print(f"multi-type pairs: {report.n_multitype_pairs}")
    print(f"mean degree {deg.mean():.1f}, median {int(q.loc[0.5])}, max {int(deg.max())}")
    print(f"\nWrote {REPORTS/'dataset_report.md'}")
    print(f"      {REPORTS/'degree_distribution.csv'}")
    print(f"      {REPORTS/'interaction_types.csv'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
