#!/usr/bin/env python3
"""Does the served model-reliance readout reproduce the frozen analysis?

DDI-Net 3.0, Phase 3. The frozen post-hoc analysis
(scripts/49_v2_interpretability.py at the tag) zeroed one branch of BIO-GINE M4
(molecular, protein or pathway) before the fusion layer and stored the seed-0
probability for every one of the 84,690 pooled test pairs in
reports/v2_interpretability/seed0_modality_contribution.csv.

The lean server now carries branch-zeroed encodings produced by the same method
(serving/engine.py::branch_zeroed_encodings). This script scores every frozen
row through the lean path and compares. The readout is exposed by the API only
because this agreement holds; the measured figures are written to
reports/v3_modality_parity.{json,md} and quoted by the API.

No training, no selection; labels are not used.
"""

from __future__ import annotations

import io
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from serving.lean import LeanEngine, _sigmoid  # noqa: E402

TAG = "v2-final-github-safe-2026-09-03"
SRC = "reports/v2_interpretability/seed0_modality_contribution.csv"
OUT_JSON = ROOT / "reports" / "v3_modality_parity.json"
OUT_MD = ROOT / "reports" / "v3_modality_parity.md"
COLUMNS = {"baseline": "baseline_prediction", "molecular": "without_molecular",
           "protein": "without_protein", "pathway": "without_pathway"}


def main() -> None:
    blob = subprocess.run(["git", "show", f"{TAG}:{SRC}"], cwd=ROOT, capture_output=True, check=True).stdout
    frozen = pd.read_csv(io.BytesIO(blob))
    eng = LeanEngine()
    if not eng.has_modality_reliance:
        raise SystemExit("lean artifact lacks branch-zeroed encodings; run python -m serving.precompute")
    ia = np.array([eng.index[a] for a in frozen["drug_a"]])
    ib = np.array([eng.index[b] for b in frozen["drug_b"]])

    res = {"source": f"{SRC} @ {TAG}", "n_rows": int(len(frozen)), "columns": {}}
    for key, col in COLUMNS.items():
        h = None if key == "baseline" else eng._h_zero[key]
        p = _sigmoid(eng._decode(ia, ib, h=h).astype(np.float64))
        d = np.abs(p - frozen[col].to_numpy(dtype=np.float64))
        res["columns"][key] = {
            "frozen_column": col,
            "max_abs_diff": float(d.max()),
            "mean_abs_diff": float(d.mean()),
            "p99_abs_diff": float(np.percentile(d, 99)),
        }
    # Deltas are what the UI shows; check them directly too.
    base = _sigmoid(eng._decode(ia, ib).astype(np.float64))
    for key in ("molecular", "protein", "pathway"):
        mine = base - _sigmoid(eng._decode(ia, ib, h=eng._h_zero[key]).astype(np.float64))
        theirs = frozen[f"{key}_delta"].to_numpy(dtype=np.float64)
        res["columns"][key]["delta_max_abs_diff"] = float(np.abs(mine - theirs).max())
    res["max_abs_diff_overall"] = max(c["max_abs_diff"] for c in res["columns"].values())

    # What the readout looks like on the frozen test pairs: which branch, when
    # removed, moves the score most. Descriptive only.
    deltas = np.stack([frozen[f"{k}_delta"].abs().to_numpy() for k in ("molecular", "protein", "pathway")], axis=1)
    top = np.argmax(deltas, axis=1)
    res["largest_reliance_share"] = {k: float((top == i).mean()) for i, k in enumerate(("molecular", "protein", "pathway"))}
    res["median_abs_delta"] = {k: float(np.median(deltas[:, i])) for i, k in enumerate(("molecular", "protein", "pathway"))}

    OUT_JSON.write_text(json.dumps(res, indent=2) + "\n")
    lines = [
        "# Model-reliance readout: parity with the frozen analysis (DDI-Net 3.0)",
        "",
        "Generated by `scripts/64_v3_modality_parity.py`. Lean server path vs",
        f"`{SRC}` at `{TAG}`, all {res['n_rows']:,} seed-0 pooled test pairs, probability space.",
        "",
        "| quantity | max abs diff | mean abs diff | 99th pct |",
        "|---|---|---|---|",
    ]
    for key, c in res["columns"].items():
        lines.append(f"| {key} | {c['max_abs_diff']:.2e} | {c['mean_abs_diff']:.2e} | {c['p99_abs_diff']:.2e} |")
    lines += [
        "",
        "Branch whose removal moves the frozen score most, share of test pairs: " +
        ", ".join(f"{k} {v:.1%}" for k, v in res["largest_reliance_share"].items()) + ".",
        "",
        "Reliance under a post-hoc perturbation is not a causal or mechanistic attribution:",
        "a zeroed branch is an input the decoder never saw in training.",
    ]
    OUT_MD.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
