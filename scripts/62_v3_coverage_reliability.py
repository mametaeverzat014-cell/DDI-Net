#!/usr/bin/env python3
"""Is BIO-GINE less reliable when a drug has no protein annotations?

DDI-Net 3.0, Phase 4. The API shows a per-pair reliability note. That note may
only rest on something measured, so this script measures it: frozen per-seed
test predictions (5 seeds, read from the tag), split by whether both drugs have
at least one drug-protein annotation in ``data/mechanism_v1`` — the same
condition the model's ``has_protein`` mask encodes (1,638 of 1,705 drugs; the
set is identical to the lean artifact's ``n_protein_annotations > 0``).

AUROC is reported next to AUPRC because the two groups differ in prevalence
(documented pairs are rarer among poorly annotated drugs), and AUPRC moves with
prevalence while AUROC does not.

Outputs: reports/v3_coverage_reliability.{json,md}
"""

from __future__ import annotations

import io
import json
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
TAG = "v2-final-github-safe-2026-09-03"
SRC = "reports/v2_final/v2_final_pair_predictions.csv"
OUT_JSON = ROOT / "reports" / "v3_coverage_reliability.json"
OUT_MD = ROOT / "reports" / "v3_coverage_reliability.md"


def main() -> None:
    edges = pd.read_parquet(ROOT / "data" / "mechanism_v1" / "drug_protein_edges.parquet")
    annotated = set(edges["drugbank_id"])
    blob = subprocess.run(["git", "show", f"{TAG}:{SRC}"], cwd=ROOT,
                          capture_output=True, check=True).stdout
    df = pd.read_csv(io.BytesIO(blob))

    res = {"source": f"{SRC} @ {TAG}", "n_annotated_drugs": len(annotated), "views": {}}
    lines = [
        "# Reliability when protein annotations are missing (DDI-Net 3.0, Phase 4)",
        "",
        "Generated by `scripts/62_v3_coverage_reliability.py` from frozen per-seed test",
        f"predictions (`{SRC}` at `{TAG}`). Mean ± SD over 5 seeds (ddof=1).",
        "",
        "| view | group | pairs | prevalence | AUROC | AUPRC |",
        "|---|---|---|---|---|---|",
    ]
    for view in ("pooled", "S3"):
        d = df[df["test_view"] == view].copy()
        both = d["drug_a"].isin(annotated) & d["drug_b"].isin(annotated)
        d["group"] = np.where(both, "both_annotated", "at_least_one_unannotated")
        out = {}
        for g, x in d.groupby("group"):
            per_seed = [
                (roc_auc_score(s["label"], s["prediction"]),
                 average_precision_score(s["label"], s["prediction"]))
                for _, s in x.groupby("seed")
            ]
            au = np.array(per_seed)
            out[g] = {
                "n_pairs": int(len(x) // x["seed"].nunique()),
                "prevalence": float(x["label"].mean()),
                "auroc_mean": float(au[:, 0].mean()), "auroc_sd": float(au[:, 0].std(ddof=1)),
                "auprc_mean": float(au[:, 1].mean()), "auprc_sd": float(au[:, 1].std(ddof=1)),
                "n_seeds": int(len(au)),
            }
            r = out[g]
            lines.append(
                f"| {view} | {g} | {r['n_pairs']:,} | {r['prevalence']:.3f} | "
                f"{r['auroc_mean']:.3f} ± {r['auroc_sd']:.3f} | {r['auprc_mean']:.3f} ± {r['auprc_sd']:.3f} |")
        res["views"][view] = out
    lines += [
        "",
        "Reading: AUROC, which does not depend on prevalence, is lower when either drug has",
        "no protein annotation, in both views. The API therefore marks such pairs as",
        "lower-reliability and quotes these numbers; it does not convert them into a",
        "per-pair confidence percentage.",
    ]
    OUT_JSON.write_text(json.dumps(res, indent=2) + "\n")
    OUT_MD.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
