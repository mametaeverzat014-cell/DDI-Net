#!/usr/bin/env python3
"""Audit: does the TDC DrugBank export order drugs the way its sentences mean?

DDI-Net 3.0. Each TDC row (ID1, ID2, type) comes with DrugBank's sentence
template, e.g. "The metabolism of #Drug2 can be decreased when combined with
#Drug1". For the eight pharmacokinetic types the sentence implies a role — the
#Drug1 slot should hold an inhibitor (or inducer) of an enzyme/transporter for
which the #Drug2 slot drug is a substrate — and DrugBank's own drug-protein
annotations record those roles. A row is *informative* when the annotations
support exactly one orientation.

Runs the same code the API applies (serving/evidence/direction.py) on the same
payload the evidence artifact is built from, and writes:
    reports/v3_tdc_direction_audit.{json,md}

The BIO-GINE model is unaffected (it trains on unordered pairs). This audit
governs only how the evidence layer words directional statements.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from serving.evidence import build as builder  # noqa: E402
from serving.evidence.direction import (  # noqa: E402
    MIN_INFORMATIVE, SYMMETRIC_TYPES, VERIFIED_THRESHOLD, audit, orientation_status,
)
from serving.evidence.records import PK_DIRECTION  # noqa: E402
from serving.evidence.store import EvidenceStore  # noqa: E402

OUT_JSON = ROOT / "reports" / "v3_tdc_direction_audit.json"
OUT_MD = ROOT / "reports" / "v3_tdc_direction_audit.md"


def main() -> None:
    payload = builder.build_payload()
    store = EvidenceStore(payload)
    table = audit(store)
    types = store.ddi_types
    n_rows = {y: 0 for y in types}
    for recs in store.records.values():
        for _, _, y in recs:
            n_rows[y] += 1
    status = {y: orientation_status(y, table) for y in types}
    rows_by_status = {s: sum(n_rows[y] for y in types if status[y] == s)
                      for s in ("symmetric", "consistent", "unverified")}

    res = {
        "source": "data/raw/drugbank.tab.gz (TDC DrugBank, PyTDC 1.1.15) + data/mechanism_v1/drug_protein_edges.parquet (DrugBank v5.1 / ChEMBL MOA roles)",
        "method": "serving/evidence/direction.py::audit",
        "verified_threshold": VERIFIED_THRESHOLD,
        "min_informative": MIN_INFORMATIVE,
        "pk_types": {
            str(y): {"template": types[y], "required_role": PK_DIRECTION[y][0],
                     "relations": sorted(PK_DIRECTION[y][1]), **table[y], "status": status[y]}
            for y in sorted(table)
        },
        "symmetric_types": sorted(SYMMETRIC_TYPES),
        "n_types": len(types),
        "n_records": sum(n_rows.values()),
        "records_by_status": rows_by_status,
    }
    OUT_JSON.write_text(json.dumps(res, indent=2) + "\n")

    lines = [
        "# TDC DrugBank export: is the drug order the order the sentence means? (DDI-Net 3.0)",
        "",
        "Generated by `scripts/63_v3_direction_audit.py` with the code the API applies",
        "(`serving/evidence/direction.py`). Informative row = DrugBank roles support exactly",
        "one orientation (one drug inhibits/induces a protein of the right kind for which the",
        "other drug is a substrate).",
        "",
        "| type | template | role in #Drug1 slot | informative rows | order matches | order reversed | consistency | status |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for y in sorted(table):
        r = res["pk_types"][str(y)]
        c = "—" if r["consistency"] is None else f"{r['consistency']:.3f}"
        lines.append(f"| {y} | {types[y]} | {r['required_role']} | {r['n_informative']:,} | "
                     f"{r['n_consistent']:,} | {r['n_reversed']:,} | {c} | {r['status']} |")
    lines += [
        "",
        f"Records by how the API words them ({res['n_records']:,} in the 1,705-drug universe):",
        "",
        f"* symmetric templates, names filled in: {rows_by_status['symmetric']:,}",
        f"* order verified (consistency ≥ {VERIFIED_THRESHOLD}), names filled in: {rows_by_status['consistent']:,}",
        f"* order not verified, rendered without naming which drug is affected: {rows_by_status['unverified']:,}",
        "",
        "Reading: the export's order is systematic per type but differs between types —",
        "kept for types 4 and 75, reversed for most rows of 47 and 73. Pharmacodynamic types",
        "cannot be checked this way. No row is flipped by the API: a correction the source",
        "did not make is not the source's statement.",
    ]
    OUT_MD.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
